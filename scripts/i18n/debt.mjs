// node scripts/i18n/debt.mjs --write: regenerates eslint-rules/i18n-debt.js from a census run.
// It only lowers: if any count is above its current ceiling (or a file absent from the table has
// one), it prints those files and exits 1 without writing.
import { existsSync, writeFileSync } from 'node:fs';
import { censusFiles, sourceFiles, countLiteralSites, countEsFields } from './literal-census.mjs';

const OUT = new URL('../../eslint-rules/i18n-debt.js', import.meta.url);
if (!process.argv.includes('--write')) {
  console.error('usage: node scripts/i18n/debt.mjs --write');
  process.exit(2);
}

const literal = countLiteralSites(censusFiles());
const es = countEsFields(sourceFiles());

if (existsSync(OUT)) {
  const { I18N_CEILINGS, ES_FIELD_CEILINGS } = await import(OUT.href);
  const raised = [];
  for (const [name, now, old] of [['literal', literal, I18N_CEILINGS], ['Es-field', es, ES_FIELD_CEILINGS]]) {
    for (const [f, n] of Object.entries(now)) if (n > (old[f] ?? 0)) raised.push(`${name} ${f}: ${n} > ${old[f] ?? 0}`);
  }
  if (raised.length) {
    console.error('Counts above their ceiling (this script only lowers):\n' + raised.join('\n'));
    process.exit(1);
  }
}

const table = (o) => '{\n' + Object.keys(o).sort().map((k) => `  '${k}': ${o[k]},\n`).join('') + '}';
writeFileSync(OUT, `// Generated by scripts/i18n/debt.mjs --write. Values only go down; a file that reaches 0 leaves the table.
// tests/repo/i18n-literal-census.test.ts and i18n-es-field-census.test.ts hold these as ceilings.
export const I18N_CEILINGS = ${table(literal)};

export const I18N_DEBT_FILES = Object.keys(I18N_CEILINGS);

export const ES_FIELD_CEILINGS = ${table(es)};
`);
console.log(`wrote ${Object.keys(literal).length} literal files, ${Object.keys(es).length} Es-field files`);
